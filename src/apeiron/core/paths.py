"""Cross-platform application paths for Apeiron.

The launcher keeps *all* of its state under a single per-user root so that
uninstallation is well defined and instances can never escape their sandbox:

    <root>/data/apeiron.db      SQLite database
    <root>/logs/                rotating native log files
    <root>/instances/<id>/      one directory per game instance
    <root>/shared/{assets,libraries,versions,java,cache}
    <root>/backups/             world archives created by the user
    <root>/downloads/           temporary download staging area

The layout is identical on every platform; only ``<root>`` differs.
"""

from __future__ import annotations

import os
import platform
import sys
from dataclasses import dataclass
from pathlib import Path

APP_DIR_NAME = "Apeiron"
_POSIX_DIR_NAME = "apeiron"


def default_root() -> Path:
    """Return the per-user application root for the current platform."""
    override = os.environ.get("APEIRON_HOME")
    if override:
        return Path(override).expanduser().resolve()

    system = platform.system()
    if system == "Windows":
        base = os.environ.get("APPDATA") or (Path.home() / "AppData" / "Roaming")
        return Path(base) / APP_DIR_NAME
    if system == "Darwin":
        return Path.home() / "Library" / "Application Support" / APP_DIR_NAME
    # Linux and other POSIX systems follow the XDG base directory spec.
    xdg = os.environ.get("XDG_DATA_HOME")
    base = Path(xdg) if xdg else (Path.home() / ".local" / "share")
    return base / _POSIX_DIR_NAME


@dataclass(frozen=True)
class AppPaths:
    """Resolved filesystem layout for one installation of Apeiron."""

    root: Path

    # ---- derived locations -------------------------------------------------
    @property
    def data(self) -> Path:
        return self.root / "data"

    @property
    def logs(self) -> Path:
        return self.root / "logs"

    @property
    def instances(self) -> Path:
        return self.root / "instances"

    @property
    def shared(self) -> Path:
        return self.root / "shared"

    @property
    def assets(self) -> Path:
        return self.shared / "assets"

    @property
    def libraries(self) -> Path:
        return self.shared / "libraries"

    @property
    def versions(self) -> Path:
        return self.shared / "versions"

    @property
    def java(self) -> Path:
        return self.shared / "java"

    @property
    def cache(self) -> Path:
        return self.shared / "cache"

    @property
    def meta(self) -> Path:
        return self.shared / "meta"

    @property
    def backups(self) -> Path:
        return self.root / "backups"

    @property
    def downloads(self) -> Path:
        return self.root / "downloads"

    @property
    def database(self) -> Path:
        return self.data / "apeiron.db"

    @property
    def config_file(self) -> Path:
        return self.data / "settings.json"

    @property
    def log_file(self) -> Path:
        return self.logs / "apeiron.log"

    # ---- operations --------------------------------------------------------
    def all_directories(self) -> tuple[Path, ...]:
        return (
            self.root,
            self.data,
            self.logs,
            self.instances,
            self.shared,
            self.assets,
            self.libraries,
            self.versions,
            self.java,
            self.cache,
            self.meta,
            self.backups,
            self.downloads,
        )

    def ensure(self) -> None:
        """Create every directory, with restrictive permissions on POSIX.

        Instances can contain account configuration, so the tree is created
        with 0700 where the platform supports it.  Failures raise ``OSError``
        with the offending path so the UI can show an actionable message.
        """
        for directory in self.all_directories():
            try:
                try:
                    directory.mkdir(mode=0o700, parents=True, exist_ok=False)
                except FileExistsError:
                    if not directory.is_dir():
                        raise
            except OSError as exc:  # pragma: no cover - depends on the host
                raise OSError(f"cannot create {directory}: {exc}") from exc

    def instance_dir(self, instance_id: str) -> Path:
        """Return the directory for ``instance_id``, rejecting traversal.

        Instance identifiers are generated by Apeiron (UUID4 hex), but they can
        also arrive from imported manifests, so the value is validated rather
        than trusted.
        """
        if not instance_id or any(sep in instance_id for sep in ("/", "\\", "..")):
            raise ValueError(f"invalid instance id: {instance_id!r}")
        candidate = (self.instances / instance_id).resolve()
        root = self.instances.resolve()
        if root != candidate and root not in candidate.parents:
            raise ValueError(f"instance path escapes the instance root: {instance_id!r}")
        return candidate

    def relative_to_root(self, path: Path) -> str:
        """Serialise ``path`` relative to the root so the DB stays portable."""
        try:
            return str(path.resolve().relative_to(self.root.resolve()))
        except ValueError:
            return str(path.resolve())

    def resolve(self, stored: str) -> Path:
        path = Path(stored)
        return path if path.is_absolute() else (self.root / path)


def current_platform_key() -> str:
    """One of ``windows``, ``macos``, ``linux`` — used by rule evaluation."""
    system = platform.system()
    if system == "Windows":
        return "windows"
    if system == "Darwin":
        return "macos"
    return "linux"


def is_frozen() -> bool:
    """True when running from a Nuitka-compiled distribution."""
    return bool(getattr(sys, "frozen", False)) or "__compiled__" in globals()
